export type Clave = keyof typeof ES
export function tx(k: Clave | string, vars?: Record<string, string | number>): string {
  let s: string = (lang.value === 'en' ? EN : ES)[k as Clave] ?? ES[k as Clave] ?? k
  if (vars) for (const v in vars) s = s.split(`{${v}}`).join(String(vars[v]))
  return s
}

const MESES = {
  es: ['ene', 'feb', 'mar', 'abr', 'may', 'jun', 'jul', 'ago', 'sep', 'oct', 'nov', 'dic'],
  en: ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'],
}
const DIAS = { es: ['dom', 'lun', 'mar', 'mié', 'jue', 'vie', 'sáb'], en: ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'] }
/** "2026-11-14" → "14 nov" / "Nov 14" */
export function fecha(f: string | null | undefined): string {
  if (!f) return '—'
  const [, m, d] = f.split('-').map(Number)
  return lang.value === 'en' ? `${MESES.en[m - 1]} ${d}` : `${d} ${MESES.es[m - 1]}`
}
/** "2026-11-14" → "sáb 14" */
export function diaSemana(f: string): string {
  const d = new Date(f + 'T12:00:00')
  return `${DIAS[lang.value === 'en' ? 'en' : 'es'][d.getDay()]} ${d.getDate()}`
}
export const fmt = (v: number) => v.toLocaleString(lang.value === 'en' ? 'en-US' : 'es-GT')
